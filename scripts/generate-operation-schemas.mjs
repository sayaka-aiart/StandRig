import ts from 'typescript';
import { readFile, writeFile } from 'node:fs/promises';
const file='packages/core/src/modelingOps.ts';
const program=ts.createProgram([file,'packages/core/src/qaCheck.ts'],{strict:true,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.NodeNext,moduleResolution:ts.ModuleResolutionKind.NodeNext,skipLibCheck:true});
const checker=program.getTypeChecker();
function named(file,name){const source=program.getSourceFile(file);const node=source.statements.find(n=>n.name?.text===name);if(!node)throw Error(name);return checker.getTypeAtLocation(node);}
const registryType=named('packages/core/src/operationRegistry.ts','ModelingActionRegistry');
const actionType=named('packages/core/src/operationRegistry.ts','ModelingOperationAction');
const actions=checker.getPropertiesOfType(registryType).map(property=>{
  const type=checker.getTypeOfSymbolAtLocation(property,property.valueDeclaration);
  const tag=type.getProperty('type');
  const tagType=tag&&checker.getTypeOfSymbolAtLocation(tag,tag.valueDeclaration);
  if(!tagType?.isStringLiteral()||tagType.value!==property.name)throw Error('Registry discriminator mismatch: '+property.name);
  const name=property.name.split('-').map(word=>word==='artmesh'?'ArtMesh':word[0].toUpperCase()+word.slice(1)).join('');
  return {key:property.name,type,name,schemaName:name[0].toLowerCase()+name.slice(1)+'Schema'};
});
function schema(type,stack=new Set()) {
  if(type===actionType)return 'actionSchema';
  const f=type.flags;
  if(f & ts.TypeFlags.StringLiteral)return `z.literal(${JSON.stringify(type.value)})`;
  if(f & ts.TypeFlags.NumberLiteral)return `z.literal(${type.value})`;
  if(f & ts.TypeFlags.BooleanLiteral)return `z.literal(${type.intrinsicName})`;
  if(f & ts.TypeFlags.String)return 'z.string()';
  if(f & ts.TypeFlags.Number)return 'z.number().finite()';
  if(f & ts.TypeFlags.Boolean)return 'z.boolean()';
  if(f & ts.TypeFlags.Null)return 'z.null()';
  if(f & ts.TypeFlags.Undefined)return 'z.undefined()';
  if(f & ts.TypeFlags.Unknown)return 'z.unknown()';
  if(f & ts.TypeFlags.Any)throw Error('Unresolved any: '+checker.typeToString(type));
  if(type.isUnion()) {
    const variants=type.types.filter(t=>!(t.flags & ts.TypeFlags.Undefined));
    const result=variants.length===1?schema(variants[0],stack):`z.union([${variants.map(t=>schema(t,stack)).join(',')}])`;
    return variants.length!==type.types.length?result+'.optional()':result;
  }
  if(checker.isTupleType(type))return `z.tuple([${checker.getTypeArguments(type).map(t=>schema(t,stack)).join(',')}])`;
  if(checker.isArrayType(type))return `z.array(${schema(checker.getTypeArguments(type)[0],stack)})`;
  if(stack.has(type))throw Error('Recursive type needs explicit schema: '+checker.typeToString(type));
  const next=new Set(stack).add(type);
  const index=checker.getIndexTypeOfType(type,ts.IndexKind.String);
  if(index)return `z.record(z.string(),${schema(index,next)})`;
  if(!(f & ts.TypeFlags.Object))throw Error('Unsupported type: '+checker.typeToString(type));
  return `z.strictObject({${checker.getPropertiesOfType(type).map(p=>{
    const t=checker.getTypeOfSymbolAtLocation(p,p.valueDeclaration??p.declarations[0]);
    let expr=schema(t,next);
    if(p.flags & ts.SymbolFlags.Optional)expr+='.optional()';
    return JSON.stringify(p.name)+':'+expr;
  }).join(',')}})`;
}
const operation=schema(named(file,'ModelingOperation'));
const qa=schema(named('packages/core/src/qaCheck.ts','QaCheckRequest'));
const header='// Generated by scripts/generate-operation-schemas.mjs. Do not edit by hand.\n';
const output=`${header}import * as z from 'zod';\nexport { READ_ONLY_BODY_ROUTES } from './legacyPolicy.mjs';\n${actions.map(a=>`export const ${a.schemaName} = ${schema(a.type)};`).join('\n')}\nexport const actionSchemas = {${actions.map(a=>JSON.stringify(a.key)+':'+a.schemaName).join(',')}};\nexport const actionSchema = z.discriminatedUnion('type', [${actions.map(a=>a.schemaName).join(',')}]);\nexport const operationSchema = ${operation};\nexport const qaSchema = ${qa};\nexport const transactionSchema = z.strictObject({expectedRevision:z.string().min(1),commit:z.boolean().default(false),operations:z.array(operationSchema).min(1).max(100),qa:qaSchema});\n`;
const declarations=`${header}import type { ZodType } from 'zod';\nimport type { ModelingOperation } from '@standrig/core/modelingOps';\nimport type { ModelingActionRegistry, ModelingOperationAction } from '@standrig/core/operationRegistry';\nimport type { QaCheckRequest } from '@standrig/core/qaCheck';\nexport type { ModelingActionRegistry, ModelingOperationAction };\n${actions.map(a=>`export type ${a.name}Action = ModelingActionRegistry[${JSON.stringify(a.key)}];\nexport const ${a.schemaName}: ZodType<${a.name}Action>;`).join('\n')}\nexport const actionSchemas: {readonly [K in keyof ModelingActionRegistry]: ZodType<ModelingActionRegistry[K]>};\nexport const actionSchema: ZodType<ModelingOperationAction>;\nexport const operationSchema: ZodType<ModelingOperation>;\nexport const qaSchema: ZodType<QaCheckRequest>;\nexport const transactionSchema: ZodType<{expectedRevision:string;commit:boolean;operations:ModelingOperation[];qa:QaCheckRequest}>;\nexport const READ_ONLY_BODY_ROUTES: Set<string>;\n`;
for(const [file,text]of [['operations.mjs',output],['index.d.ts',declarations]]) {
  const target='packages/contracts/src/'+file;
  if(process.argv.includes('--check')) {if((await readFile(target,'utf8')).replaceAll('\r\n','\n')!==text)throw Error('Operation contracts are stale: '+target);}
  else await writeFile(target,text);
}
console.log('Strict operation and QA schemas '+(process.argv.includes('--check')?'verified':'generated'));
